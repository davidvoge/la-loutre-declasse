export function parseHourSort(s) {
  const m = String(s || '').match(/(\d{1,2})h(\d{2})?/);
  if (!m) return 9999;
  let h = parseInt(m[1], 10);
  const mm = parseInt(m[2] || '0', 10);
  if (h < 6) h += 24;
  return h * 60 + mm;
}

